// One-off generator for src/utils/showcase/routes.ts — real road geometry for the showcase fleet.
// Uses the public OSRM demo server once, at authoring time; the app never calls it. Usage: node scripts/build-showcase-routes.mjs
import { writeFileSync } from 'node:fs';

const YARDS = [
  [24.8465, 66.9963], // 0 Karachi
  [31.5204, 74.3587], // 1 Lahore
  [33.6844, 73.0479], // 2 Islamabad
  [31.4504, 73.135], // 3 Faisalabad
  [30.1575, 71.5249], // 4 Multan
  [34.0151, 71.5249], // 5 Peshawar
  [32.4945, 74.5229], // 6 Sialkot
  [25.396, 68.3578], // 7 Hyderabad
];
const PAIRS = [[0, 1], [1, 2], [0, 4], [1, 3], [2, 5], [1, 4], [1, 6], [0, 7], [0, 3], [2, 6], [3, 4]];

const sleep = ms => new Promise(r => setTimeout(r, ms));
const enc = (pts) => {
  let out = '', plat = 0, plon = 0;
  const e = v => { v = v < 0 ? ~(v << 1) : v << 1; let s = ''; while (v >= 0x20) { s += String.fromCharCode((0x20 | (v & 0x1f)) + 63); v >>= 5; } return s + String.fromCharCode(v + 63); };
  for (const [lat, lon] of pts) { const la = Math.round(lat * 1e5), lo = Math.round(lon * 1e5); out += e(la - plat) + e(lo - plon); plat = la; plon = lo; }
  return out;
};
const dp = (pts, tol) => {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts[pts.length - 1]];
  let idx = 0, dmax = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const [x0, y0] = pts[i], [x1, y1] = a, [x2, y2] = b;
    const dx = x2 - x1, dy = y2 - y1, l = dx * dx + dy * dy || 1e-12;
    const t = Math.max(0, Math.min(1, ((x0 - x1) * dx + (y0 - y1) * dy) / l));
    const d = Math.hypot(x0 - (x1 + t * dx), y0 - (y1 + t * dy));
    if (d > dmax) { dmax = d; idx = i; }
  }
  return dmax > tol ? [...dp(pts.slice(0, idx + 1), tol).slice(0, -1), ...dp(pts.slice(idx), tol)] : [a, b];
};
async function route(coords) {
  const q = coords.map(([lat, lon]) => `${lon},${lat}`).join(';');
  for (let i = 0; i < 4; i++) {
    const r = await fetch(`https://router.project-osrm.org/route/v1/driving/${q}?overview=full&geometries=geojson`);
    const j = await r.json();
    if (j.code === 'Ok') { const rt = j.routes[0]; return { km: Math.round(rt.distance / 100) / 10, min: Math.round(rt.duration / 60), pts: rt.geometry.coordinates.map(([lon, lat]) => [lat, lon]) }; }
    await sleep(1500);
  }
  throw new Error('route failed ' + q);
}

const out = { highways: {}, loops: {} };
for (const [a, b] of PAIRS) {
  const r = await route([YARDS[a], YARDS[b]]);
  const pts = dp(r.pts, 0.0007);
  out.highways[`${a}-${b}`] = { km: r.km, min: r.min, line: enc(pts) };
  console.log(`${a}-${b}`, r.km, 'km', pts.length, 'pts');
  await sleep(1100);
}
let seed = 7;
const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
for (let y = 0; y < YARDS.length; y++) {
  out.loops[y] = [];
  for (let k = 0; k < 3; k++) {
    const off = () => [(rnd() - 0.5) * 0.16, (rnd() - 0.5) * 0.16];
    const [la, lo] = YARDS[y];
    const w1 = [la + off()[0], lo + off()[1]], w2 = [la + off()[0], lo + off()[1]];
    const r = await route([YARDS[y], w1, w2, YARDS[y]]);
    const pts = dp(r.pts, 0.0002);
    out.loops[y].push({ km: r.km, min: r.min, line: enc(pts) });
    console.log(`loop ${y}.${k}`, r.km, 'km', pts.length, 'pts');
    await sleep(1100);
  }
}
const src = `/* eslint-disable */
// GENERATED by scripts/build-showcase-routes.mjs (OSRM, run once). Do not edit by hand.
// Google-polyline (precision 5) road geometry between the showcase yards, plus local delivery loops per yard.
export const HIGHWAY_ROUTES: Record<string, { km: number; min: number; line: string }> = ${JSON.stringify(out.highways, null, 1)};

export const YARD_LOOPS: Record<string, { km: number; min: number; line: string }[]> = ${JSON.stringify(out.loops, null, 1)};
`;
writeFileSync('src/utils/showcase/routes.ts', src);
console.log('written', src.length, 'bytes');
