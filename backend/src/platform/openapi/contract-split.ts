type Json = any;

/**
 * Splits the one big generated document into one self-contained OpenAPI 3.1
 * file per tag/module (D-0140) — the frontend session doesn't need to load
 * an 860 KB spec to check one endpoint, and a per-module file is small
 * enough to hand over or open on demand. Each module file is a complete,
 * independently valid document (its own `openapi`/`info`/`servers`/
 * `security`/`components`) — schemas are **copied in**, not cross-file
 * `$ref`'d, so a file never needs another file to make sense of it. The
 * small amount of duplication (a handful of schemas like `ErrorResponse`
 * or the login-style `User` appear in several module files) is the
 * trade-off for that; `contract-file.ts`'s `mergeModules()` is the inverse
 * — reconstructs one logical document from the files for CI drift-checking
 * and live conformance, so nothing is lost by splitting for humans.
 */

function refsIn(node: unknown, acc: Set<string>): void {
  if (Array.isArray(node)) node.forEach(n => refsIn(n, acc));
  else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) {
      if (k === '$ref' && typeof v === 'string') acc.add(v.replace('#/components/schemas/', ''));
      else refsIn(v, acc);
    }
  }
}

export interface ModuleFile {
  tag: string;
  /** File-safe name (the tag itself — already kebab-case). */
  fileName: string;
  document: Json;
  operationCount: number;
}

/** `document` is the full assembled contract (`buildContract()`'s `.document`). */
export function splitByTag(document: Json): ModuleFile[] {
  const byTag = new Map<string, Json>();
  for (const [path, item] of Object.entries<Json>(document.paths)) {
    for (const [method, op] of Object.entries<Json>(item)) {
      const tag: string = op.tags?.[0] ?? 'misc';
      const target = byTag.get(tag) ?? {};
      byTag.set(tag, target);
      (target[path] ??= {})[method] = op;
    }
  }

  const allSchemas: Json = document.components?.schemas ?? {};
  const files: ModuleFile[] = [];
  for (const [tag, paths] of [...byTag.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const referenced = new Set<string>();
    refsIn(paths, referenced);
    // Transitive closure: a referenced schema can itself reference others.
    const queue = [...referenced];
    while (queue.length) {
      const name = queue.pop()!;
      const child = new Set<string>();
      refsIn(allSchemas[name], child);
      for (const c of child) {
        if (!referenced.has(c)) {
          referenced.add(c);
          queue.push(c);
        }
      }
    }
    const schemas: Json = {};
    for (const name of [...referenced].sort())
      if (allSchemas[name]) schemas[name] = allSchemas[name];

    const opCount: number = Object.values<Json>(paths).reduce(
      (n: number, item) => n + Object.keys(item).length,
      0
    );
    const moduleDoc: Json = {
      openapi: document.openapi,
      info: {
        title: `ConvoyAI API — ${tag}`,
        version: document.info.version,
        description: `One module of the ConvoyAI API contract (${opCount} operations). Part of \`openapi.yaml\` (the index) + \`API_CONTRACT.md\` (conventions, realtime, known problems) — read those first if this is your only file. Regenerated by \`npm run openapi:write\` in \`node-backend/\`; do not hand-edit.`,
      },
      servers: document.servers,
      security: document.security,
      tags: (document.tags ?? []).filter((t: Json) => t.name === tag),
      paths: paths,
      components: {
        securitySchemes: document.components.securitySchemes,
        responses: document.components.responses,
        schemas,
      },
    };
    files.push({ tag, fileName: `${tag}.yaml`, document: moduleDoc, operationCount: opCount });
  }
  return files;
}

/** The inverse of `splitByTag` — folds every module file's paths+schemas back into one logical document, for diffing/conformance against what the code generates. `index` is the root file's document (info/servers/security/tags only, no paths). */
export function mergeModules(index: Json, modules: ModuleFile[]): Json {
  const paths: Json = {};
  const schemas: Json = {};
  for (const m of modules) {
    // A path can legitimately be split across two module files by method (e.g. `/devices/{id}`:
    // GET is tagged "assets" — D-0128's `componentsDevices` handler — while PUT/DELETE are tagged
    // "devices") — merge at the method level, never overwrite one module's methods with another's.
    for (const [path, item] of Object.entries<Json>(m.document.paths)) {
      paths[path] = { ...(paths[path] ?? {}), ...item };
    }
    Object.assign(schemas, m.document.components.schemas);
  }
  const sortedPaths: Json = {};
  for (const p of Object.keys(paths).sort()) sortedPaths[p] = paths[p];
  const sortedSchemas: Json = {};
  for (const n of Object.keys(schemas).sort()) sortedSchemas[n] = schemas[n];
  return {
    ...index,
    paths: sortedPaths,
    components: { ...index.components, schemas: sortedSchemas },
  };
}
