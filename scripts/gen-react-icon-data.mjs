#!/usr/bin/env node
// Generates src/assets/icons/ReactIcon/iconData.ts from iconManifest.json.
//
// WHY: the ReactIcon/*Icon.tsx wrappers used to `import { MdAir } from 'react-icons/md'` etc. across ~20
// different react-icons packs (md is 2 MB, pi 5.7 MB, ... 85 MB total). Compiling any route that reaches
// them (e.g. /roles-permission via CardRole -> AddMemberForm -> IconWrapper's ~64 dynamic imports) made
// webpack dev parse every pack at once: 4 GB+ RSS and a dev-server crash. Each react-icons icon is just
// `GenIcon(<svg tree>)`, so we copy only the ~70 trees we use into one tiny local file. The rendered SVG
// is identical (see --verify).
//
// To add an icon: add "IconName": "pack" (e.g. "MdAir": "md") to iconManifest.json, run
//   npm run gen:icons
// and import it from './iconData' in the wrapper.
//
// To REVERT this optimization (wrappers back to importing straight from react-icons):
//   node scripts/gen-react-icon-data.mjs --revert
// then optionally delete iconData.ts (nothing imports it afterwards). See DEV_PERFORMANCE.md §2b/§2d.
//
// usage: node scripts/gen-react-icon-data.mjs [--verify | --revert]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'src/assets/icons/ReactIcon');
const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'iconManifest.json'), 'utf8'));
const verify = process.argv.includes('--verify');

if (process.argv.includes('--revert')) {
  // Undo: `import { X } from './iconData'` -> `import { X } from 'react-icons/<pack>'` in every wrapper.
  let n = 0;
  for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.tsx'))) {
    const file = path.join(dir, f);
    const src = fs.readFileSync(file, 'utf8');
    const next = src.replace(/import \{ ([A-Za-z0-9]+) \} from '\.\/iconData';/, (_, name) => {
      if (!manifest[name]) throw new Error(`${f}: ${name} missing from iconManifest.json`);
      return `import { ${name} } from 'react-icons/${manifest[name]}';`;
    });
    if (next !== src) { fs.writeFileSync(file, next); n++; }
  }
  console.log(`reverted ${n} wrapper files to import from react-icons/<pack> directly`);
  process.exit(0);
}

const packSrc = {};
function tree(name, pack) {
  packSrc[pack] ??= fs.readFileSync(path.join(root, 'node_modules/react-icons', pack, 'index.mjs'), 'utf8');
  const re = new RegExp(`export function ${name} \\(props\\) \\{\\s*return GenIcon\\((\\{.*?\\})\\)\\(props\\);\\s*\\};?\\n`);
  const m = packSrc[pack].match(re);
  if (!m) throw new Error(`icon ${name} not found in react-icons/${pack}`);
  return JSON.parse(m[1]);
}

const entries = Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b));
const out = [
  '// GENERATED by scripts/gen-react-icon-data.mjs from iconManifest.json — do not edit by hand.',
  '// Local copies of the react-icons SVG trees we use, so webpack never has to parse whole icon packs.',
  "import { GenIcon } from 'react-icons/lib';",
  '',
  ...entries.map(([name, pack]) => `export const ${name} = GenIcon(${JSON.stringify(tree(name, pack))}); // react-icons/${pack}`),
  '',
].join('\n');
fs.writeFileSync(path.join(dir, 'iconData.ts'), out);
console.log(`wrote iconData.ts: ${entries.length} icons, ${(out.length / 1024).toFixed(1)} KB`);

if (verify) {
  const React = (await import(pathToFileURL(path.join(root, 'node_modules/react/index.js')))).default;
  const { renderToStaticMarkup } = (await import(pathToFileURL(path.join(root, 'node_modules/react-dom/server.node.js')))).default ?? {};
  const { GenIcon } = await import(pathToFileURL(path.join(root, 'node_modules/react-icons/lib/index.mjs')));
  let bad = 0;
  for (const [name, pack] of entries) {
    const orig = (await import(pathToFileURL(path.join(root, 'node_modules/react-icons', pack, 'index.mjs'))))[name];
    const mine = GenIcon(tree(name, pack));
    const props = { className: 'h-6 w-6', size: 20, title: 't' };
    const a = renderToStaticMarkup(React.createElement(orig, props));
    const b = renderToStaticMarkup(React.createElement(mine, props));
    if (a !== b) { bad++; console.error('MISMATCH', name); }
  }
  console.log(bad ? `VERIFY FAILED (${bad})` : `VERIFY OK: all ${entries.length} icons render byte-identical to react-icons`);
  process.exit(bad ? 1 : 0);
}
